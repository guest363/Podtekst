#!/usr/bin/env bash
# P11-аудит: показывает добавленные в diff строки с комментариями,
# чтобы автор оставил только «зачем» (ограничение платформы, контракт
# формата, калибровка порога), SAFETY:/shortcut: или ссылку на правило.
# Советующий, а не запрещающий: решение принимает человек, скрипт лишь
# исключает «забыл проверить». Игнорирует собранный бандл ui/web/static.
set -u
ref="${1:-HEAD}"
top="$(git rev-parse --show-toplevel 2>/dev/null)" || exit 0
cd "$top" || exit 0
out="$(git diff --unified=0 "$ref" -- . ':!ui/web/static' \
  | grep "^+" | grep -v "^+++" \
  | grep -E "//|/\*" | grep -v "://" || true)"
if [ -z "$out" ]; then
  echo "P11: добавленных комментариев нет — чисто."
  exit 0
fi
printf '%s\n' "$out"
n="$(printf '%s\n' "$out" | wc -l)"
echo "---"
echo "P11: добавленных строк с комментариями: $n — каждая обязана быть «зачем», иначе удалить."
